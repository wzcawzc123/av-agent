def seed_presales_knowledge(session) -> int:
    """幂等写入预置文档；返回新增条数（已存在则跳过）。"""
    existing = {d["title"] for d in list_documents(session)}
    added = 0
    for doc in PRESALES_DOCUMENTS:
        if doc["title"] in existing:
            continue
        register_document(
            session,
            title=doc["title"],
            doc_type=doc["doc_type"],
            file_path="",
            excerpt=doc["excerpt"],
            meta=doc["meta"],
        )
        added += 1
    if added:
        session.commit()
    return added
